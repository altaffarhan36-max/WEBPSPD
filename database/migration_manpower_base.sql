 UNIQUE KEY uq_manpower_employee_no (employee_no),
 KEY idx_manpower_placement (placement),
 KEY idx_manpower_status (employment_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
